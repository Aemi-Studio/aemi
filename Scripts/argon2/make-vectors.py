#!/usr/bin/env python3
"""Writes Tests/AemiArgon2Tests/ReferenceVectors.swift: BLAKE2b from Python's hashlib, Argon2 from OpenSSL 3.2+ (`openssl kdf`),
both implementations independent of AemiArgon2. Deterministic: the same seed gives the same file.
Usage, from the repository root (the committed file is the output after swift-format):
  OPENSSL=/opt/homebrew/bin/openssl python3 Scripts/argon2/make-vectors.py
  swift-format format --in-place --configuration .swift-format Tests/AemiArgon2Tests/ReferenceVectors.swift"""
import hashlib, os, random, subprocess, sys

rng = random.Random(0x13)
openssl = os.environ.get("OPENSSL", "openssl")

def blob(n): return bytes(rng.randrange(256) for _ in range(n))
def swift(b): return '"' + b.hex() + '"'

blake = []
for n in [0, 1, 3, 63, 64, 127, 128, 129, 255, 256, 257, 1000]:
    for out in [1, 20, 32, 48, 64]:
        for keyed in [False, True]:
            key = blob(rng.choice([1, 16, 32, 64])) if keyed else b""
            data = blob(n)
            blake.append((data, key, out, hashlib.blake2b(data, digest_size=out, key=key).digest()))

argon = []
for i in range(60):
    variant = ["ARGON2D", "ARGON2I", "ARGON2ID"][i % 3]
    lanes = rng.choice([1, 1, 2, 3, 4, 8])
    memory = rng.randrange(8 * lanes, 8 * lanes + 300)
    passes = rng.choice([1, 2, 3, 4])
    tag = rng.choice([4, 16, 32, 63, 64, 65, 100, 128, 129, 257, 1024])
    pw, salt = blob(rng.choice([0, 1, 8, 32, 100])), blob(rng.choice([8, 16, 33]))
    secret, ad = blob(rng.choice([0, 0, 8, 32])), blob(rng.choice([0, 0, 12]))
    args = [openssl, "kdf", "-keylen", str(tag), "-kdfopt", f"hexsalt:{salt.hex()}", "-kdfopt", f"iter:{passes}",
            "-kdfopt", f"memcost:{memory}", "-kdfopt", f"lanes:{lanes}", "-kdfopt", "threads:1"]
    if pw: args += ["-kdfopt", f"hexpass:{pw.hex()}"]
    else: args += ["-kdfopt", "pass:"]
    if secret: args += ["-kdfopt", f"hexsecret:{secret.hex()}"]
    if ad: args += ["-kdfopt", f"hexad:{ad.hex()}"]
    out = subprocess.run(args + [variant], capture_output=True, text=True, check=True).stdout.strip().replace(":", "")
    argon.append((variant[6:].lower(), lanes, memory, passes, pw, salt, secret, ad, bytes.fromhex(out)))

lines = ["// Generated by Scripts/argon2/make-vectors.py: BLAKE2b by Python's hashlib, Argon2 by OpenSSL, as hex. Do not edit.",
         "// swiftlint:disable file_length", "", "@testable import AemiArgon2", "", "enum ReferenceVectors {",
         "    static let blake2b: [(data: String, key: String, length: Int, digest: String)] = ["]
lines += [f"        ({swift(d)}, {swift(k)}, {o}, {swift(h)})," for d, k, o, h in blake]
lines += ["    ]", "", "    // swiftlint:disable:next large_tuple",
          "    static let argon2: [(variant: Argon2.Variant, lanes: Int, memoryKiB: Int, passes: Int, password: String, salt: String, secret: String, associatedData: String, tag: String)] = ["]
lines += [f"        (.{v}, {l}, {m}, {t}, {swift(p)}, {swift(s)}, {swift(k)}, {swift(x)}, {swift(o)})," for v, l, m, t, p, s, k, x, o in argon]
lines += ["    ]", "}", ""]
open("Tests/AemiArgon2Tests/ReferenceVectors.swift", "w").write("\n".join(lines))
print(len(blake), "BLAKE2b,", len(argon), "Argon2 vectors")
