// Generates Sources/AemiUnicode/GeneratedUnicodeTables.swift: the character classes and canonical decompositions of
// the transformers.js-parity tokenizer, taken from the JavaScript engine itself, so they match its behaviour by
// construction. Run with Bun (JavaScriptCore), the engine the parity fixtures come from:
//
//   bun Scripts/unicode/gen-unicode-tables.mjs > Sources/AemiUnicode/GeneratedUnicodeTables.swift
//
// What each class is, as @huggingface/transformers 4.2.0 tests it (BertNormalizer, BertPreTokenizer):
//   cleanTextRemoval  _clean_text drops U+0000, U+FFFD and controls: \p{Cc}, \p{Cf}, \p{Co} (\p{Cs} has no scalar),
//                     but not tab, line feed or carriage return
//   jsWhitespace      /\s/
//   nonspacingMark    \p{Mn}, which strip_accents removes after NFD
//   bertPunctuation   _is_punctuation: \p{P} and the ASCII symbols ! to /, : to @, [ to `, { to ~
//   chineseChar       _is_chinese_char's CJK blocks
//   nfd               String.prototype.normalize("NFD") of every scalar it changes, Hangul syllables excluded (the
//                     lookup decomposes them algorithmically)
// Rewritten 2026-11-01 from the generated file's own description, since the original was not kept (aemi ADR 0024).

const scalars = function* () {
    for (let cp = 0; cp <= 0x10ffff; cp++) {
        if (cp >= 0xd800 && cp <= 0xdfff) continue;
        yield cp;
    }
};

function ranges(test) {
    const out = [];
    let count = 0;
    for (const cp of scalars()) {
        if (!test(cp, String.fromCodePoint(cp))) continue;
        count++;
        const last = out.length - 1;
        if (last >= 1 && out[last] === cp - 1) out[last] = cp;
        else out.push(cp, cp);
    }
    return { values: out, count };
}

const control = /^\p{Cc}|\p{Cf}|\p{Co}|\p{Cs}$/u;
const punctuation = /^[\p{P}\u0021-\u002F\u003A-\u0040\u005B-\u0060\u007B-\u007E]$/u;
const chinese = [[0x4e00, 0x9fff], [0x3400, 0x4dbf], [0x20000, 0x2a6df], [0x2a700, 0x2b73f], [0x2b740, 0x2b81f],
    [0x2b820, 0x2ceaf], [0xf900, 0xfaff], [0x2f800, 0x2fa1f]];

const classes = {
    cleanTextRemoval: ranges((cp, ch) => cp === 0 || cp === 0xfffd || (!'\t\n\r'.includes(ch) && control.test(ch))),
    jsWhitespace: ranges((_, ch) => /^\s$/.test(ch)),
    nonspacingMark: ranges((_, ch) => /^\p{Mn}$/u.test(ch)),
    bertPunctuation: ranges((_, ch) => punctuation.test(ch)),
    chineseChar: ranges((cp) => chinese.some(([lo, hi]) => cp >= lo && cp <= hi)),
};

const index = [], offsets = [0], payload = [];
for (const cp of scalars()) {
    if (cp >= 0xac00 && cp <= 0xd7a3) continue;
    const ch = String.fromCodePoint(cp);
    const nfd = ch.normalize('NFD');
    if (nfd === ch) continue;
    index.push(cp);
    for (const part of nfd) payload.push(part.codePointAt(0));
    offsets.push(payload.length);
}

const hex = (n) => '0x' + n.toString(16).toUpperCase();
function table(name, values, doc = []) {
    const rows = [];
    for (let i = 0; i < values.length; i += 10) rows.push('        ' + values.slice(i, i + 10).map(hex).join(', '));
    return [...doc.map((line) => '    /// ' + line), `    static let ${name}: [UInt32] = [`, rows.join(',\n'), '    ]'].join('\n');
}

const lines = [
    '// Generated by Scripts/unicode/gen-unicode-tables.mjs — DO NOT EDIT BY HAND.',
    '// Regenerate: bun Scripts/unicode/gen-unicode-tables.mjs > Sources/AemiUnicode/GeneratedUnicodeTables.swift',
    '//',
    `// Engine: Bun ${Bun.version} (JavaScriptCore) — the same engine that produces`,
    '// test/fixtures/tokenizer-parity/cases.json, so these tables match the parity',
    "// target's Unicode behavior by construction (see the generator header for the",
    '// captured @huggingface/transformers 4.2.0 semantics).',
    '//',
    ...Object.entries(classes).map(([name, c]) => `// ${name}: ${c.count} scalars / ${c.values.length / 2} ranges`),
    `// nfd: ${index.length} entries / ${payload.length} payload scalars`,
    '',
    '/// Engine-derived character classes and canonical decompositions for the',
    '/// transformers.js-parity tokenizer. Range tables are flat inclusive',
    '/// [lo, hi] pairs sorted ascending; see UnicodeSets.swift for lookups.',
    'enum UnicodeTables {',
    Object.entries(classes).map(([name, c]) => table(name, c.values)).join('\n\n'),
    '',
    table('nfdIndex', index, [
        'Scalars with a non-trivial canonical decomposition (Hangul syllables',
        'excluded — decomposed algorithmically). Fully expanded recursively, in',
        'canonical order, exactly as String.normalize("NFD") returns them.',
    ]),
    '',
    table('nfdOffsets', offsets, ["nfdOffsets[i]..<nfdOffsets[i+1] bounds nfdIndex[i]'s payload slice."]),
    '',
    table('nfdPayload', payload),
    '}',
    '',
];
process.stdout.write(lines.join('\n'));
