// Generates Sources/AemiUnicode/Generated/UnicodeDataTables.swift from Go's unicode package: general categories, scripts, the category
// aliases Go's regexp accepts, and simple case-folding orbits, for AemiUnicode's `UnicodeData` (aemi ADR 0018; moved from AemiRegex). One source, one Unicode version (printed in the file), so categories,
// scripts and folding can never disagree with each other, and the data is the same data the Go oracle uses.
//
// The generator also checks the rules the Swift side uses to derive sets, and fails if Go disagrees: the one-letter groups are unions of
// their two-letter categories, LC is Lu|Ll|Lt, and Cn is the complement of everything else.
//
// No recursion. Run from the repository root:
//   go run scripts/unicode/gen.go > Sources/AemiUnicode/Generated/UnicodeDataTables.swift
package main

import (
	"fmt"
	"os"
	"sort"
	"strings"
	"unicode"
)

type span struct{ lo, hi uint32 }

// expand lists the ranges of a table, honouring strides, merged and ascending.
func expand(t *unicode.RangeTable) []span {
	var scalars []uint32
	for _, r := range t.R16 {
		for c := uint32(r.Lo); c <= uint32(r.Hi); c += uint32(r.Stride) {
			scalars = append(scalars, c)
		}
	}
	for _, r := range t.R32 {
		for c := r.Lo; c <= r.Hi; c += r.Stride {
			scalars = append(scalars, c)
		}
	}
	sort.Slice(scalars, func(i, j int) bool { return scalars[i] < scalars[j] })
	var out []span
	for _, c := range scalars {
		if n := len(out); n > 0 && out[n-1].hi+1 == c {
			out[n-1].hi = c
		} else {
			out = append(out, span{c, c})
		}
	}
	return out
}

func membership(t *unicode.RangeTable) []bool {
	m := make([]bool, 0x110000)
	for _, s := range expand(t) {
		for c := s.lo; c <= s.hi; c++ {
			m[c] = true
		}
	}
	return m
}

func union(tables ...*unicode.RangeTable) []bool {
	m := make([]bool, 0x110000)
	for _, t := range tables {
		for c, in := range membership(t) {
			if in {
				m[c] = true
			}
		}
	}
	return m
}

func same(name string, a, b []bool) {
	for c := range a {
		if a[c] != b[c] {
			fmt.Fprintf(os.Stderr, "derivation rule broken for %s at U+%04X\n", name, c)
			os.Exit(1)
		}
	}
}

// group writes a number as swift-format would: 7 or more digits are grouped in threes with underscores.
func group(n uint32) string {
	text := fmt.Sprint(n)
	if len(text) < 7 {
		return text
	}
	var out []byte
	for i, c := range []byte(text) {
		if i > 0 && (len(text)-i)%3 == 0 {
			out = append(out, '_')
		}
		out = append(out, c)
	}
	return string(out)
}

// emit writes an array literal with short lines, so the file needs no reformatting and a regenerate-and-diff check is exact.
func emit(name, doc, elementType string, values []string) {
	fmt.Printf("\n    /// %s\n    static let %s: [%s] = [\n", doc, name, elementType)
	for i := 0; i < len(values); i += 12 {
		end := i + 12
		if end > len(values) {
			end = len(values)
		}
		suffix := ","
		if end == len(values) {
			suffix = ""
		}
		fmt.Printf("        %s%s\n", strings.Join(values[i:end], ", "), suffix)
	}
	fmt.Printf("    ]\n")
}

// emitWords writes a space-separated word list as a multi-line string literal, one short line at a time.
func emitWords(name, doc string, words []string) {
	fmt.Printf("\n    /// %s\n    static let %s = \"\"\"\n", doc, name)
	line := ""
	for _, w := range words {
		if len(line)+len(w)+1 > 100 && line != "" {
			fmt.Printf("        %s\n", line)
			line = ""
		}
		if line != "" {
			line += " "
		}
		line += w
	}
	fmt.Printf("        %s\n        \"\"\"\n", line)
}

func main() {
	codes := []string{"Lu", "Ll", "Lt", "Lm", "Lo", "Mn", "Mc", "Me", "Nd", "Nl", "No", "Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po", "Sm", "Sc", "Sk", "So", "Zs", "Zl", "Zp", "Cc", "Cf", "Cs", "Co"}
	cat := func(n string) *unicode.RangeTable { return unicode.Categories[n] }

	// The derivation rules, checked against Go's own tables.
	groups := map[string][]string{"L": {"Lu", "Ll", "Lt", "Lm", "Lo"}, "M": {"Mn", "Mc", "Me"}, "N": {"Nd", "Nl", "No"},
		"P": {"Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po"}, "S": {"Sm", "Sc", "Sk", "So"}, "Z": {"Zs", "Zl", "Zp"}}
	for g, members := range groups {
		var ts []*unicode.RangeTable
		for _, m := range members {
			ts = append(ts, cat(m))
		}
		same(g, membership(cat(g)), union(ts...))
	}
	var all []*unicode.RangeTable
	for _, c := range codes {
		all = append(all, cat(c))
	}
	assigned := union(all...)
	cn := make([]bool, 0x110000)
	for c := range cn {
		cn[c] = !assigned[c]
	}
	same("Cn", membership(cat("Cn")), cn)
	same("C", membership(cat("C")), union(cat("Cc"), cat("Cf"), cat("Co"), cat("Cs"), cat("Cn")))
	same("LC", membership(cat("LC")), union(cat("Lu"), cat("Ll"), cat("Lt")))

	fmt.Printf("// Generated by scripts/unicode/gen.go from Go's unicode package. Do not edit; regenerate with\n")
	fmt.Printf("//   go run scripts/unicode/gen.go > Sources/AemiUnicode/Generated/UnicodeDataTables.swift\n")
	fmt.Printf("// Unicode %s. Categories, scripts, aliases and case folding all come from this one source.\n\n", unicode.Version)
	fmt.Printf("enum UnicodeDataTables {\n    static let unicodeVersion = %q\n", unicode.Version)

	// Categories: the 29 two-letter categories except Cn, which is the complement of the rest.
	var data []string
	var offsets []string
	for _, c := range codes {
		offsets = append(offsets, fmt.Sprint(len(data)/2))
		for _, s := range expand(cat(c)) {
			data = append(data, group(s.lo), group(s.hi))
		}
	}
	offsets = append(offsets, fmt.Sprint(len(data)/2))
	emitWords("categoryCodes", "The two-letter categories, in the order of `categoryOffsets`. `Cn` is not here: it is everything else.", codes)
	emit("categoryOffsets", "Range index at which each category starts in `categoryData`, and the end.", "Int", offsets)
	emit("categoryData", "Inclusive `lo, hi` pairs, category after category.", "UInt32", data)

	// Category aliases as Go's regexp accepts them.
	var aliases []string
	for k, v := range unicode.CategoryAliases {
		aliases = append(aliases, k+"="+v)
	}
	sort.Strings(aliases)
	emitWords("categoryAliases", "`Alias=Code` pairs from Go's `unicode.CategoryAliases`.", aliases)

	// Scripts.
	var names []string
	for n := range unicode.Scripts {
		names = append(names, n)
	}
	sort.Strings(names)
	data, offsets = nil, nil
	for _, n := range names {
		offsets = append(offsets, fmt.Sprint(len(data)/2))
		for _, s := range expand(unicode.Scripts[n]) {
			data = append(data, group(s.lo), group(s.hi))
		}
	}
	offsets = append(offsets, fmt.Sprint(len(data)/2))
	emitWords("scriptNames", "Script names, in the order of `scriptOffsets`.", names)
	emit("scriptOffsets", "Range index at which each script starts in `scriptData`, and the end.", "Int", offsets)
	emit("scriptData", "Inclusive `lo, hi` pairs, script after script.", "UInt32", data)

	// Case-folding orbits: each orbit ascending and ended by 0; an index of (scalar, start) pairs sorted by scalar.
	var orbits []string
	type entry struct{ scalar, start uint32 }
	var index []entry
	for r := rune(0); r <= 0x10FFFF; r++ {
		if unicode.SimpleFold(r) == r {
			continue
		}
		least := r
		for c := unicode.SimpleFold(r); c != r; c = unicode.SimpleFold(c) {
			if c < least {
				least = c
			}
		}
		if least != r {
			continue
		}
		members := []rune{r}
		for c := unicode.SimpleFold(r); c != r; c = unicode.SimpleFold(c) {
			members = append(members, c)
		}
		sort.Slice(members, func(i, j int) bool { return members[i] < members[j] })
		start := uint32(len(orbits))
		for _, m := range members {
			index = append(index, entry{uint32(m), start})
			orbits = append(orbits, group(uint32(m)))
		}
		orbits = append(orbits, "0")
	}
	sort.Slice(index, func(i, j int) bool { return index[i].scalar < index[j].scalar })
	var pairs []string
	for _, e := range index {
		pairs = append(pairs, group(e.scalar), group(e.start))
	}
	emit("foldOrbits", "The members of each simple case-folding orbit, ascending, each orbit ended by 0.", "UInt32", orbits)
	emit("foldIndex", "`scalar, start` pairs sorted by scalar: where in `foldOrbits` the scalar's orbit starts.", "UInt32", pairs)
	fmt.Printf("}\n")
}
